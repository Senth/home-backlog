#!/usr/bin/env node
//
// Generates functions/src/icon-names.ts from the glyph map the installed
// @expo/vector-icons ships, so the API validates `icon` against the same set
// the app's picker offers (#256). A Renovate bump that adds glyphs must not
// leave the API rejecting an icon the picker can still pick.
//
// Usage:   node scripts/gen-icon-names.mjs [--check]
// Exit:    0 = written, or in --check mode already in step
//          1 = --check found the file out of step

import { readFileSync, writeFileSync } from "node:fs";

const SOURCE =
	"node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons/glyphmaps/MaterialCommunityIcons.json";
const TARGET = "functions/src/icon-names.ts";

const glyphmap = JSON.parse(readFileSync(SOURCE, "utf8"));
const names = Object.keys(glyphmap).sort();

const file = `/**
 * Generated by \`yarn icon-names\` (scripts/gen-icon-names.mjs) from the
 * installed @expo/vector-icons glyphmap MaterialCommunityIcons.json —
 * do not edit. Regenerate and commit when that dependency is bumped.
 *
 * Every MaterialCommunityIcons glyph name the picker can offer; the label
 * verbs (#256) validate \`icon\` against this set.
 */

export const iconNames: ReadonlySet<string> = new Set([
${names.map((name) => `\t"${name}",`).join("\n")}
]);
`;

if (process.argv.includes("--check")) {
	const current = readFileSync(TARGET, "utf8");
	if (current !== file) {
		console.error(
			"functions/src/icon-names.ts is out of step with the installed glyphmap. Run `yarn icon-names` and commit the result.",
		);
		process.exit(1);
	}
	console.log("functions/src/icon-names.ts is in step with the glyphmap.");
} else {
	writeFileSync(TARGET, file);
	console.log(`Wrote ${TARGET} with ${names.length} glyph names.`);
}
